print(arr_sum)
# [[왼쪽 위 합계, 오른쪽 위 합계],
#  [왼쪽 아래 합계, 오른쪽 아래 합계]]

# 3. 합계가 가장 큰 구역의 위치를 (행, 열) 형태로 출력해주세요.
